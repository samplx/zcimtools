     1    INSTK(7),ITRAN(256),OTRAN(64)
      COMMON /FILES/IBUFF,OBUFF,IBP,OBP,INPTR,
     1    INSTK,ITRAN,OTRAN
      I=GNC(0)
      ACCLEN = 0
      IF (STYPE .NE. CONT) GO TO 51
      GO TO (100,200,51,51,499), TYPE
C     DEBLANK INPUT
50    I = GNC(0)
51    IF (I .EQ. 0) GO TO 100
      GO TO (50,300,300,300,300,300,300,300,300,300,300,
     1      200,200,200,200,200,200,200,200,200,200,
     2      200,200,200,200,200,200,200,200,200,200,
     3      200,200,200,200,200,200,
     4      400,400,400,400,400,400,400,400,400,400,
     5      400), I
C     END OF FILE
100   TYPE = EOFLAG
      GO TO 999
C     IDENTIFIER
200   TYPE = IDENT
210   ACCLEN = ACCLEN + 1
      ACCUM(ACCLEN) = I
      IF (ACCLEN .GE. 32) GO TO 220
215   I = GNC(0)
C     CHECK FOR $ IN AN IDENTIFIER
      IF (I.EQ.38) GO TO 215
      IF ((I .GE. 2) .AND. (I .LE. 37)) GO TO 210
      IBP = IBP -1
      STYPE = 0
      GO TO 999
220   STYPE = CONT
      GO TO 999
C
C
C     NUMBER
300   TYPE = NUMB
      STYPE = 0
310   ACCLEN = ACCLEN +1
      ACCUM(ACCLEN) = I
      IF (ACCLEN .EQ. 32) GO TO 350
313   I = GNC(0)
C     CHECK FOR $ IN A NUMBER
      IF (I.EQ.38) GO TO 313
      IF ((I .GE. 2) .AND. (I .LE. 17)) GO TO 310
C     CHECK RADIX
      IF (I .EQ. 19) STYPE = 16
      IF (I .EQ. 28) STYPE = 8
      IF (I .EQ. 26) STYPE = 8
      IF (STYPE .NE. 0) GO TO 325
      IF (ACCUM(ACCLEN) .EQ. 13) GO TO 315
      IF (ACCUM(ACCLEN) .EQ. 15) GO TO 318
      STYPE = 10
      GO TO 320
315   STYPE = 2
      ACCLEN = ACCLEN - 1
      GO TO 320
318   STYPE = 10
      ACCLEN = ACCLEN -1
320   IBP = IBP - 1
325       DO 330 I=1,ACCLEN
          J = ACCUM(I) -2
          IF (J.GE.STYPE) GO TO 340
330       CONTINUE
      GO TO 999
340   STYPE = 1
      GO TO 999
350   STYPE = 1
351   I = GNC(0)
      IF ((I .GE. 2) .AND. (I .LE. 17)) GO TO 351
      IBP = IBP -1
      GO TO 999
C     SPECIAL CHARACTER (TEST FOR QUOTE)
400   CONTINUE
      IF (I .EQ. 46) GO TO 500
      TYPE = SPECL
      ACCLEN = 1
      ACCUM(1) = I
      IF (I .NE. 41) GO TO 999
      I = GNC(0)
C     LOOK FOR COMMENT
      IF (I .EQ. 47) GO TO 410
      IBP = IBP -1
      GO TO 999
C     COMMENT FOUND
410   I = GNC (0)
      IF (I .EQ. 0) GO TO 100
      IF (I .NE. 47) GO TO 410
      I = GNC(0)
      IF (I .NE. 41) GO TO 410
      ACCLEN = 0
      GO TO 50
C     CONTINUE WITH STRING
499   IBP = IBP -1
C     STRING QUOTE
500   TYPE = STR
      ACCUM(1) = 1
510   I = GNC(0)
      IF (I .EQ. 46) GO TO 530
520   ACCLEN = ACCLEN +1
      CALL PAD(1,1,1)
      ACCUM(ACCLEN) = I
      IF (ACCLEN .LT. 32) GO TO 510
      STYPE = CONT
      GO TO 999
C     STRING QUOTE FOUND (ENDING, MAYBE)
530   I = GNC(0)
      IF (I. EQ. 46) GO TO 520
      IBP = IBP -1
      STYPE = 0
      IF (ACCLEN.NE.1) GO TO 999
C
C CONVERT 1 CHARACTER STRING TO NUMERIC REPRESENTATION
C OF ASCII CHARACTER
C
      I = ACCUM(1)
      I = ASCII(I)
      ACCUM(2) = MOD(I,10) + 2
      ACCUM(1) = I/10 + 2
      ACCLEN = 2
      STYPE = 10
      TYPE = NUMB
999   RETURN
      END
      SUBROUTINE CONV(PREC)
