      COMMON /SCANC/ACCLEN,ACCUM,TYPE,STYPE,EOFLAG,
     1    IDENT,NUMB,SPECL,STR,CONT,VALUE,ASCII
      IF (STYPE .LE. 1) GO TO 200
      VALUE = 0
          DO 100 I=1,ACCLEN
          J = ACCUM(I) - 2
100       VALUE = VALUE * STYPE + J
      IF (PREC .LE. 0) GO TO 999
      I = 2**PREC
      IF (VALUE .LT. I) GO TO 999
200   VALUE = -1
999   RETURN
      END
