      SUBROUTINE DISYM(ICC,LOC)
C     DISPLAY THE SYMBOL CLOSEST TO THE LOCATION LOC
      INTEGER RADIX(26),RADIXV(5),DEBASE
      COMMON /RADIX/RADIX,RADIXV,DEBASE
      INTEGER BUFF(32)
      INTEGER ACCLEN,ACCUM(32),TYPE,STYPE,EOFLAG,
     1    IDENT,NUMB,SPECL,STR,CONT,VALUE,ASCII(52)
      COMMON /SCANC/ACCLEN,ACCUM,TYPE,STYPE,EOFLAG,
     1    IDENT,NUMB,SPECL,STR,CONT,VALUE,ASCII
      INTEGER ERRSET,ENDST,ABORT
      COMMON /MISC/ICB,ICT,ERRSET,ENDST,ABORT
      INTEGER GET
C
      IF (ICB.EQ.0) GO TO 9998
      MDIST = 65536
      MLOC = 0
      I = 0
100   IF (I.GE.ICB) GO TO 200
          J = GET(I)
          K = I + J + 1
          KP = GET(K) * 256 + GET(K+1)
          IF (IABS(LOC-KP).GE.IABS(MDIST)) GO TO 150
              MDIST = LOC - KP
              MLOC = I
150       I = K + 2
      GO TO 100
C
200       J = GET(MLOC)
          DO 300 I=1,J
           KP = MLOC+I
          KP = GET(KP)
          BUFF(I) = KP
300       CONTINUE
C
      CALL FORM(ICC,BUFF,1,J,32)
      IF (MDIST.EQ.0) GO TO 400
      IF (MDIST.LT.0) I = 45
      IF (MDIST.GT.0) I = 44
      CALL PAD(1,I,1)
      MDIST = IABS(MDIST)
      CALL CONOUT(2,-16,MDIST,DEBASE)
400   CONTINUE
      CALL WRITEL(0)
      GO TO 9999
9998  ERRSET = 5
9999  RETURN
      END
      SUBROUTINE INITAL
      INTEGER WDSIZE,WFACT,TWO11,FACT(5)
      INTEGER MAXMEM,MEMTOP,MEMBOT,MEM(8192),MAXVM
      COMMON /FACTOR/WDSIZE,WFACT,TWO11,FACT
      COMMON /MEMORY/MAXMEM,MEMTOP,MEMBOT,MEM,MAXVM
      INTEGER I,J,K
      WFACT = WDSIZE/11
      MAXVM = MAXMEM*WFACT - 1
      MEMTOP = MAXVM+1
      MEMBOT =  -1
C
          DO 5 I=1,5
          FACT(I) = 0
5         CONTINUE
C
C
      FACT(WFACT) = 1
      J= WFACT-1
          DO 10 I=1,J
          K = WFACT - I
          FACT(K) = FACT(K+1) * TWO11
10        CONTINUE
C
          DO 15 I=1,MAXMEM
          MEM(I) = 0
15        CONTINUE
      RETURN
      END
      INTEGER FUNCTION GET(I)
      INTEGER I
      INTEGER WDSIZE,WFACT,TWO11,FACT(5)
      INTEGER MAXMEM,MEMTOP,MEMBOT,MEM(8192),MAXVM
      COMMON /FACTOR/WDSIZE,WFACT,TWO11,FACT
      COMMON /MEMORY/MAXMEM,MEMTOP,MEMBOT,MEM,MAXVM
      INTEGER J,K
      J = I/WFACT+1
      IF (J .GT. MAXMEM) CALL ERROR(1)
      J = MEM(J)
      K = MOD(I,WFACT)+1
      GET = MOD(J/FACT(K),TWO11)
      RETURN
      END
      SUBROUTINE PUT(I,X)
      INTEGER I,X
      INTEGER WDSIZE,WFACT,TWO11,FACT(5)
      INTEGER MAXMEM,MEMTOP,MEMBOT,MEM(8192),MAXVM
      COMMON /FACTOR/WDSIZE,WFACT,TWO11,FACT
      COMMON /MEMORY/MAXMEM,MEMTOP,MEMBOT,MEM,MAXVM
      J = I/WFACT+1
      IF (J .GT. MAXMEM) CALL ERROR(1)
      M = MEM(J)
      K = MOD(I,WFACT)+1
      MH = 0
      IF (K .EQ. 1) GO TO 10
      IFACT = FACT(K-1)
      MH = (M/IFACT)*IFACT
10    IFACT = FACT(K)
      M = MOD(M,IFACT)
      MEM(J) = MH +X*IFACT+M
      RETURN
      END
      INTEGER FUNCTION ALLOC(I)
      INTEGER I
      INTEGER WDSIZE,WFACT,TWO11,FACT(5)
      INTEGER MAXMEM,MEMTOP,MEMBOT,MEM(8192),MAXVM
      COMMON /FACTOR/WDSIZE,WFACT,TWO11,FACT
      COMMON /MEMORY/MAXMEM,MEMTOP,MEMBOT,MEM,MAXVM
      IF (I .LT. 0) GO TO 10
C     ALLOCATION IS FROM BOTTOM
      ALLOC = MEMBOT +1
      MEMBOT = MEMBOT + I
      IF (MEMBOT .GT. MEMTOP) CALL ERROR(2)
      RETURN
C
C     ALLOCATION IS FROM TOP
10    MEMTOP=MEMTOP + I
      IF (MEMTOP .LE. MEMBOT) CALL ERROR(2)
      ALLOC = MEMTOP
      RETURN
      END
      SUBROUTINE SCAN
      INTEGER GNC
      INTEGER ACCLEN,ACCUM(32),TYPE,STYPE,EOFLAG,
