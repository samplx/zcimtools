      LOGICAL FUNCTION WRMEM(ADDR,NB,VAL,PC)
      INTEGER ADDR,NB,VAL,PC,GET,GVAL(2)
      INTEGER REG(16),REGW(16),TIMER,CYCLE,INCYC,LBREAK,BREAK,NOSTOP,
     1    INTR,IPC,INS,INTTOG,INTW,INTSY(27)
      COMMON /REG/REG,REGW,TIMER,CYCLE,INCYC,LBREAK,BREAK,NOSTOP,
     1    INTR,IPC,INS,INTTOG,INTW,INTSY
      INTEGER ERRSET,ENDST,ABORT
      COMMON /MISC/ICB,ICT,ERRSET,ENDST,ABORT
C
      IVAL = MOD(VAL,65536)
      I = ADDR + ICB
      IF (I.LE.ICT) GO TO 50
          BREAK = -1
          GO TO 150
50    INB = NB
      WRMEM = .FALSE.
C
C     CHECK FOR ALTER FLAG
100   IF (INB.LE.0) GO TO 300
      J = GET(I)/256
      IF (J.EQ.0) GO TO 200
C     CHECK ALTER
      IF (MOD(J,2).EQ.0) GO TO 200
C     CHECK PC
      IF (LBREAK.EQ.PC) GO TO 200
          BREAK = 3
150       WRMEM = .TRUE.
          GO TO 500
C
200   GVAL(INB) = J*256
      INB = INB - 1
      I = I + 1
      GO TO 100
C
C     NOW WRITE VALUE INTO MEMORY
300   INB = NB
      I = ADDR + ICB
400   IF (INB .LE. 0) GO TO 500
      JP = GVAL(INB) + MOD(IVAL,256)
      IVAL = IVAL/256
      INB = INB-1
      CALL PUT(I,JP)
      I = I+1
      GO TO 400
C
500   RETURN
      END
      LOGICAL FUNCTION RDMEM(ADDR,NB,VAL,PC)
      INTEGER ADDR,NB,VAL,PC,GET
      INTEGER REG(16),REGW(16),TIMER,CYCLE,INCYC,LBREAK,BREAK,NOSTOP,
     1    INTR,IPC,INS,INTTOG,INTW,INTSY(27)
      COMMON /REG/REG,REGW,TIMER,CYCLE,INCYC,LBREAK,BREAK,NOSTOP,
     1    INTR,IPC,INS,INTTOG,INTW,INTSY
      INTEGER ERRSET,ENDST,ABORT
      COMMON /MISC/ICB,ICT,ERRSET,ENDST,ABORT
C
      I = ADDR + ICB
      IF (I.LE.ICT) GO TO 50
          BREAK = -4
          GO TO 300
50    INB = NB
      VAL = 0
      K = 1
100   IF (INB.LE.0) GO TO 300
      J = GET(I)
      JP = J/256
      IF (JP.EQ.0) GO TO 200
C     MAY BE A BREAK POINT
      JP = MOD(JP/2,2)
      J = MOD(J,256)
      IF (JP.EQ.0) GO TO 200
C     CHECK LAST BREAK POINT
      IF (LBREAK.EQ.PC) GO TO 200
          BREAK = 2
          GO TO 300
200   INB = INB-1
      VAL = K*J + VAL
      K = 256
      I = I + 1
      GO TO 100
C
300   RDMEM = BREAK.NE.0
      RETURN
      END
      LOGICAL FUNCTION PRTBRK(PTYPE,PNUM,OPAND)
