      INTEGER FUNCTION FIXBIT(WD,LOC,VAL)
      INTEGER WD,LOC,VAL
C     LET WD BE A 12-BIT WORD W(12),W(11),...,W(1)
C     FIXBIT CHANGES THE VALUE OF W(LOC) TO VAL
C     (THE RIGHTMOST 8 BITS OF WD ARE ALWAYS PRESERVED)
C
C     POWERS OF TWO ARE SHOWN LITERALLY IN THE HOPE THAT YOUR
C     COMPILER SUBSTITUTES SHIFT OPERATIONS.  OTHERWISE IT WOULD
C     BE WORTHWHILE GOING TO ASSEMBLY LANGUAGE, OR AT LEAST
C     PRECOMPUTING THE POWERS.
C
      I = (WD/2**LOC)*2**LOC
      I = I + VAL*2**(LOC-1)
      FIXBIT = I + MOD(WD,2**(LOC-1))
      RETURN
      END
