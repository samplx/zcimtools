C         WRITE PORT PNUM = NUMBER
          CALL FORM(0,PDISP,1,4,4)
          CALL PAD(1,1,1)
          CALL CONOUT(2,-5,PNUM,DEBASE)
          CALL PAD(1,1,1)
          CALL PAD(1,39,1)
          CALL PAD(1,1,1)
          CALL CONOUT(2,-5,OPAND,DEBASE)
          GO TO 9999
